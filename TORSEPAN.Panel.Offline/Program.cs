using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
using Microsoft.AspNetCore.Components.Authorization;
using TORSEPAN.Panel.Components;
using TORSEPAN.Panel.Services;
using TORSEPAN.Panel.Services.Api;
using TORSEPAN.Panel.Services.Auth;
using TORSEPAN.Panel.Authentication;
var builder=WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");builder.RootComponents.Add<HeadOutlet>("head::after");
builder.Services.AddAuthorizationCore();builder.Services.AddCascadingAuthenticationState();
builder.Services.AddScoped<TokenStorage>();
builder.Services.AddScoped<AuthenticationStateProvider,AuthStateProvider>();
builder.Services.AddScoped<OfflineHttpHandler>();
builder.Services.AddScoped(sp=>new HttpClient(sp.GetRequiredService<OfflineHttpHandler>()){BaseAddress=new Uri("https://appassets.androidplatform.net/api/")});
builder.Services.AddScoped<ApiClient>();
builder.Services.AddScoped<AuthenticationService>();builder.Services.AddScoped<IAuthService>(sp=>sp.GetRequiredService<AuthenticationService>());
builder.Services.AddSingleton<OfflineDataRefresh>();builder.Services.AddSingleton<ILocalDataRefresh>(sp=>sp.GetRequiredService<OfflineDataRefresh>());
builder.Services.AddScoped<IUserService, UserService>();
builder.Services.AddScoped<ProductionService>();
builder.Services.AddScoped<HandpanService>();
builder.Services.AddScoped<BowlService>();
builder.Services.AddScoped<MaterialService>();
builder.Services.AddScoped<PayrollService>();
builder.Services.AddScoped<PayrollExclusionService>();
builder.Services.AddScoped<DesignService>();
builder.Services.AddScoped<HandpanPhotoService>();
builder.Services.AddScoped<AccountingService>();
builder.Services.AddScoped<ScaleService>();
builder.Services.AddScoped<OrderService>();
builder.Services.AddScoped<ReportService>();
builder.Services.AddScoped<SalesAttributionService>();
builder.Services.AddScoped<AdminProductionEditService>();
builder.Services.AddScoped<PersonalWorkspaceService>();
builder.Services.AddScoped<MarketingService>();
builder.Services.AddScoped<UserApiClient>();
await builder.Build().RunAsync();
