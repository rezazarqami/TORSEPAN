"""Generate shared navy overrides for green paint left in legacy panel components."""
import colorsys
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
color = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)')
def navy(match):
    raw = match.group()
    try:
        if raw.startswith('#'):
            h = raw[1:]
            if len(h) in (3, 4): h = ''.join(c * 2 for c in h)
            rgb = [int(h[i:i+2], 16) for i in (0, 2, 4)]
            alpha = int(h[6:8],16) / 255 if len(h) == 8 else 1
        else:
            values = [float(x.strip()) for x in raw[raw.index('(')+1:-1].split(',')]
            rgb, alpha = values[:3], values[3] if len(values) == 4 else 1
        hue, light, saturation = colorsys.rgb_to_hls(*(v / 255 for v in rgb))
        if not (70 <= hue * 360 <= 185 and saturation > .12): return raw
        target = (3,30,67) if light < .60 else (96,120,143) if light < .8 else (215,229,244) if light < .92 else (237,244,252)
        return '#%02x%02x%02x' % target if alpha == 1 else 'rgba(%s,%g)' % (','.join(map(str,target)), alpha)
    except (ValueError, IndexError): return raw
def selectors(value):
    # Commas inside :is(), :not() and attribute values do not split selector lists.
    depth, quote, start = 0, None, 0
    for index, char in enumerate(value):
        if quote:
            if char == quote: quote = None
        elif char in ('"', "'"): quote = char
        elif char in '([': depth += 1
        elif char in ')]': depth -= 1
        elif char == ',' and depth == 0:
            yield value[start:index].strip(); start = index + 1
    yield value[start:].strip()
rules = []
files = sorted((root / 'TORSEPAN.Panel/Components').rglob('*.razor.css'))
# Reports retains a small inline style block for its dynamic grid.
files += [root / 'TORSEPAN.Panel/Components/Pages/Reports.razor']
for path in files:
    source = path.read_text(encoding='utf-8-sig')
    if path.suffix == '.razor': source = ''.join(re.findall(r'<style>(.*?)</style>',source,re.S))
    source = re.sub(r'/\*.*?\*/','',source,flags=re.S)
    page_rules = []
    for selector, body in re.findall(r'([^{}]+)\{([^{}]*)\}',source):
        selector = selector.strip()
        if not selector or selector.startswith('@') or re.match(r'^[\d%]', selector): continue
        declarations = []
        for declaration in body.split(';'):
            if ':' not in declaration: continue
            prop, value = declaration.split(':',1)
            mapped = color.sub(navy,value)
            if mapped != value: declarations.append(prop.strip()+':'+mapped.strip())
        if declarations:
            scoped = ','.join('body .theme-shell '+s.strip() for s in selectors(selector))
            page_rules.append(scoped+'{'+ ';'.join(declarations)+'}')
    if page_rules: rules.append('/* '+path.stem+' */\n'+'\n'.join(page_rules))
target = root / 'TORSEPAN.Panel/wwwroot/theme-palette.css'
target.write_text('/* Generated by scripts/build-theme-palette.py. Legacy green paint uses the approved navy palette. */\n'+'\n'.join(rules)+'\n')
print(len(rules),'component palettes,',target.stat().st_size,'bytes')
